import torch
import torchvision
import torchvision.transforms as transforms
import torch.nn as nn
import torch.optim as optim
from torch.optim.lr_scheduler import CosineAnnealingLR
import torch.nn.functional as F
from tqdm import tqdm
import time
import os
import numpy as np

# 修复多进程问题和过时参数
if __name__ == '__main__':
    # 数据增强和预处理 - 针对STL-10的96x96图像
    train_transform = transforms.Compose([
        transforms.RandomCrop(96, padding=8),
        transforms.RandomHorizontalFlip(p=0.5),
        transforms.RandomRotation(10),
        transforms.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.2, hue=0.1),
        transforms.ToTensor(),
        transforms.Normalize((0.4467, 0.4398, 0.4066), (0.2603, 0.2566, 0.2713)),  # STL-10的统计量
    ])

    test_transform = transforms.Compose([
        transforms.ToTensor(),
        transforms.Normalize((0.4467, 0.4398, 0.4066), (0.2603, 0.2566, 0.2713)),
    ])

    # 加载STL-10数据集
    print("Loading STL-10 dataset...")
    train_dataset = torchvision.datasets.STL10(
        root='./data',
        split='train',
        download=True,
        transform=train_transform
    )

    test_dataset = torchvision.datasets.STL10(
        root='./data',
        split='test',
        download=True,
        transform=test_transform
    )

    # 数据加载器 - 在Windows上设置num_workers=0
    batch_size = 64
    num_workers = 0  # Windows上设为0避免多进程问题

    train_loader = torch.utils.data.DataLoader(
        train_dataset, batch_size=batch_size, shuffle=True, num_workers=num_workers
    )

    test_loader = torch.utils.data.DataLoader(
        test_dataset, batch_size=batch_size, shuffle=False, num_workers=num_workers
    )

    # STL-10类别
    classes = ['airplane', 'bird', 'car', 'cat', 'deer',
               'dog', 'horse', 'monkey', 'ship', 'truck']

    print(f"Training samples: {len(train_dataset)}")
    print(f"Test samples: {len(test_dataset)}")


    # 定义模型 - 修复过时的pretrained参数
    class STL10Model(nn.Module):
        def __init__(self, num_classes=10):
            super().__init__()
            # 使用新的权重API替代过时的pretrained参数
            self.backbone = torchvision.models.resnet18(
                weights=torchvision.models.ResNet18_Weights.IMAGENET1K_V1
            )

            # 修改第一层卷积，适应STL-10的96x96输入
            self.backbone.conv1 = nn.Conv2d(3, 64, kernel_size=7, stride=2, padding=3, bias=False)

            # 替换全连接层
            in_features = self.backbone.fc.in_features
            self.backbone.fc = nn.Sequential(
                nn.Dropout(0.3),
                nn.Linear(in_features, 512),
                nn.ReLU(inplace=True),
                nn.Dropout(0.2),
                nn.Linear(512, num_classes)
            )

        def forward(self, x):
            return self.backbone(x)


    # 自定义CNN模型（备选）
    class STL10CNN(nn.Module):
        def __init__(self, num_classes=10):
            super().__init__()
            self.features = nn.Sequential(
                # 第一层
                nn.Conv2d(3, 64, 3, padding=1),
                nn.BatchNorm2d(64),
                nn.ReLU(inplace=True),
                nn.Conv2d(64, 64, 3, padding=1),
                nn.BatchNorm2d(64),
                nn.ReLU(inplace=True),
                nn.MaxPool2d(2),
                nn.Dropout(0.2),

                # 第二层
                nn.Conv2d(64, 128, 3, padding=1),
                nn.BatchNorm2d(128),
                nn.ReLU(inplace=True),
                nn.Conv2d(128, 128, 3, padding=1),
                nn.BatchNorm2d(128),
                nn.ReLU(inplace=True),
                nn.MaxPool2d(2),
                nn.Dropout(0.3),

                # 第三层
                nn.Conv2d(128, 256, 3, padding=1),
                nn.BatchNorm2d(256),
                nn.ReLU(inplace=True),
                nn.Conv2d(256, 256, 3, padding=1),
                nn.BatchNorm2d(256),
                nn.ReLU(inplace=True),
                nn.MaxPool2d(2),
                nn.Dropout(0.4),

                # 第四层
                nn.Conv2d(256, 512, 3, padding=1),
                nn.BatchNorm2d(512),
                nn.ReLU(inplace=True),
                nn.Conv2d(512, 512, 3, padding=1),
                nn.BatchNorm2d(512),
                nn.ReLU(inplace=True),
                nn.AdaptiveAvgPool2d((1, 1)),
            )

            self.classifier = nn.Sequential(
                nn.Dropout(0.5),
                nn.Linear(512, 256),
                nn.ReLU(inplace=True),
                nn.Dropout(0.3),
                nn.Linear(256, num_classes)
            )

        def forward(self, x):
            x = self.features(x)
            x = x.view(x.size(0), -1)
            x = self.classifier(x)
            return x


    # 设置设备
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")

    # 初始化模型
    model = STL10Model(num_classes=10).to(device)
    # 或者使用自定义CNN: model = STL10CNN(num_classes=10).to(device)

    # 损失函数和优化器
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.AdamW(model.parameters(), lr=0.001, weight_decay=1e-4)
    scheduler = CosineAnnealingLR(optimizer, T_max=50)

    # 训练参数
    num_epochs = 50
    best_accuracy = 0


    # 训练函数
    def train_epoch(model, dataloader, criterion, optimizer, device):
        model.train()
        running_loss = 0.0
        correct = 0
        total = 0

        pbar = tqdm(dataloader, desc='Training')
        for batch_idx, (inputs, targets) in enumerate(pbar):
            inputs, targets = inputs.to(device), targets.to(device)

            optimizer.zero_grad()
            outputs = model(inputs)
            loss = criterion(outputs, targets)
            loss.backward()

            # 梯度裁剪
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)

            optimizer.step()

            running_loss += loss.item()
            _, predicted = outputs.max(1)
            total += targets.size(0)
            correct += predicted.eq(targets).sum().item()

            pbar.set_postfix({
                'Loss': f'{running_loss / (batch_idx + 1):.3f}',
                'Acc': f'{100. * correct / total:.2f}%'
            })

        return running_loss / len(dataloader), 100. * correct / total


    # 测试函数
    def test_epoch(model, dataloader, criterion, device, return_predictions=False):
        model.eval()
        running_loss = 0.0
        correct = 0
        total = 0
        all_predictions = []
        all_targets = []

        with torch.no_grad():
            pbar = tqdm(dataloader, desc='Testing')
            for batch_idx, (inputs, targets) in enumerate(pbar):
                inputs, targets = inputs.to(device), targets.to(device)

                outputs = model(inputs)
                loss = criterion(outputs, targets)

                running_loss += loss.item()
                _, predicted = outputs.max(1)
                total += targets.size(0)
                correct += predicted.eq(targets).sum().item()

                if return_predictions:
                    all_predictions.extend(predicted.cpu().numpy())
                    all_targets.extend(targets.cpu().numpy())

                pbar.set_postfix({
                    'Loss': f'{running_loss / (batch_idx + 1):.3f}',
                    'Acc': f'{100. * correct / total:.2f}%'
                })

        result = (running_loss / len(dataloader), 100. * correct / total)
        if return_predictions:
            result += (all_predictions, all_targets)
        return result


    # 开始训练
    print("Starting training...")
    train_losses = []
    test_losses = []
    train_accuracies = []
    test_accuracies = []

    for epoch in range(num_epochs):
        start_time = time.time()

        print(f"\nEpoch {epoch + 1}/{num_epochs}")
        print("-" * 50)

        # 训练一个epoch
        train_loss, train_acc = train_epoch(model, train_loader, criterion, optimizer, device)

        # 测试
        test_loss, test_acc = test_epoch(model, test_loader, criterion, device)

        # 更新学习率
        scheduler.step()

        epoch_time = time.time() - start_time

        # 记录指标
        train_losses.append(train_loss)
        test_losses.append(test_loss)
        train_accuracies.append(train_acc)
        test_accuracies.append(test_acc)

        print(f"Epoch {epoch + 1} completed in {epoch_time:.2f}s")
        print(f"Train Loss: {train_loss:.4f}, Train Acc: {train_acc:.2f}%")
        print(f"Test Loss: {test_loss:.4f}, Test Acc: {test_acc:.2f}%")
        print(f"Learning Rate: {scheduler.get_last_lr()[0]:.6f}")

        # 保存最佳模型
        if test_acc > best_accuracy:
            best_accuracy = test_acc
            torch.save({
                'epoch': epoch,
                'model_state_dict': model.state_dict(),
                'optimizer_state_dict': optimizer.state_dict(),
                'scheduler_state_dict': scheduler.state_dict(),
                'accuracy': test_acc,
                'loss': test_loss,
                'train_losses': train_losses,
                'test_losses': test_losses,
                'train_accuracies': train_accuracies,
                'test_accuracies': test_accuracies
            }, 'best_stl10_model.pth')
            print(f"New best model saved with accuracy: {test_acc:.2f}%")

    print(f"\nTraining completed. Best accuracy: {best_accuracy:.2f}%")

    # 加载最佳模型进行最终评估
    print("\nLoading best model for final evaluation...")
    checkpoint = torch.load('best_stl10_model.pth')
    model.load_state_dict(checkpoint['model_state_dict'])

    # 最终测试并获取预测结果
    final_loss, final_accuracy, all_preds, all_targets = test_epoch(
        model, test_loader, criterion, device, return_predictions=True
    )

    print(f"\nFinal Test Accuracy: {final_accuracy:.2f}%")

    # 计算每个类别的准确率
    print("\nPer-class accuracy:")
    class_correct = [0] * 10
    class_total = [0] * 10

    for pred, target in zip(all_preds, all_targets):
        class_total[target] += 1
        if pred == target:
            class_correct[target] += 1

    for i in range(10):
        accuracy = 100 * class_correct[i] / class_total[i] if class_total[i] > 0 else 0
        print(f"{classes[i]:10s}: {accuracy:.2f}% ({class_correct[i]}/{class_total[i]})")